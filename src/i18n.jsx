export function localizeScienceHindi(value) {
  if (typeof value !== "string") return value;
  return HI_SCIENCE_TERMS.reduce((text, [english, hindi]) => {
    const escaped = english.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    return text.replace(new RegExp(`\\b${escaped}\\b`, "gi"), hindi);
  }, value);
}

export function translate(language, english) {
  if (language !== "hi" || !english) return english;
  if (HI[english]) return HI[english];
  const exactClass = english.match(/^Class (\d+)$/);
  if (exactClass) return `कक्षा ${exactClass[1]}`;
  const uppercaseClass = english.match(/^CLASS (\d+)(.*)$/);
  if (uppercaseClass) return `कक्षा ${uppercaseClass[1]}${uppercaseClass[2] ? ` ${uppercaseClass[2]}` : ""}`;
  const questionProgress = english.match(/^Question (\d+) of (\d+)$/);
  if (questionProgress) return `प्रश्न ${questionProgress[1]} / ${questionProgress[2]}`;
  const pageProgress = english.match(/^Page (\d+) of (\d+)$/);
  if (pageProgress) return `पृष्ठ ${pageProgress[1]} / ${pageProgress[2]}`;
  return english;
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try { return localStorage.getItem(STORAGE_KEY) === "hi" ? "hi" : "en"; }
    catch { return "en"; }
  });
  useEffect(() => {
    document.documentElement.lang = language;
    const pageTitle = language === "hi"
      ? "Chemistry World | कक्षा 9–12 की वर्चुअल रसायन प्रयोगशाला"
      : "Chemistry World | Interactive NCERT Chemistry Lab";
    document.title = pageTitle;
    const metadata = {
      description: language === "hi"
        ? "कक्षा 9–12 की इंटरैक्टिव 3D NCERT रसायन विज्ञान लैब। रसायन चुनें, अभिक्रियाएँ देखें और कक्षा-वार क्विज़ दें।"
        : "Explore Chemistry World, an interactive 3D NCERT chemistry lab for Classes 9–12. Collect chemicals, explore reaction models, and take class-wise quizzes.",
      "og:title": pageTitle,
      "og:description": language === "hi"
        ? "वर्चुअल रसायन विज्ञान लैब में घूमें, NCERT अभिक्रिया मॉडल देखें और अपना ज्ञान जाँचें।"
        : "Walk through a virtual chemistry lab, explore NCERT reaction models, and test what you know.",
      "twitter:title": pageTitle,
      "twitter:description": language === "hi"
        ? "कक्षा 9–12 के लिए चलकर देखने वाली वर्चुअल रसायन विज्ञान लैब।"
        : "A walk-through virtual chemistry lab for Classes 9–12.",
    };
    Object.entries(metadata).forEach(([key, content]) => {
      const selector = key.startsWith("og:") || key.startsWith("twitter:")
        ? `meta[property="${key}"]` : `meta[name="${key}"]`;
      document.querySelector(selector)?.setAttribute("content", content);
    });
    try { localStorage.setItem(STORAGE_KEY, language); } catch { /* private browsing can disable storage */ }
  }, [language]);
  const value = useMemo(() => ({ language, setLanguage, t: (english) => translate(language, english) }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
